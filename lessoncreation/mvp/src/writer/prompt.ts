/**
 * Prompts for the writer stage. The writer converts a LessonSkeleton
 * (structured JSON) into a v2 `.txt` file — the format the existing
 * `parseTextLessonV2` in the main repo accepts and the boss's team
 * hand-writes today.
 *
 * The writer receives:
 *   - The full skeleton (all 10 exercises × 4 sections)
 *   - A short reference lesson embedded in the system prompt as a
 *     concrete format exemplar
 *
 * The writer produces:
 *   - Freeform Hebrew text in v2 format — NOT JSON.
 *   - Validation happens downstream by calling parseTextLessonV2 on
 *     the output and checking structural invariants.
 */
import type { LessonSkeleton } from '../planner/schema.js'
import { V2_FORMAT_REFERENCE } from './format-reference.js'

const SYSTEM_PROMPT = `\
אתה כותב תוכן שיעור למתמטיקה בעברית לפי פורמט קפדני שלנו (פורמט v2).
המערכת קיבלה שלד תכנון של השיעור (10 תרגילים, 4 סעיפים כל אחד), ותפקידך: להפוך את השלד ל-**קובץ .txt מלא** שיכול להיטען למערכת שלנו.

# פורמט v2 — מבנה חובה

## מבנה כללי
כל תרגיל מחולק ל-5 בלוקים תחומים ב-\`====\` (שווים):
1. \`[ תרגיל N - נתוני פתיחה ]\` — טקסט פתיחה + שרטוט בסיס משותף לתרגיל (אופציונלי)
2. \`[ סעיף א' - שאלת ברירה יחידה ]\` או וריאציה
3. \`[ סעיף ב' - שאלת ברירה יחידה ]\` או וריאציה
4. \`[ סעיף ג' - שאלת ברירה יחידה ]\` (3 אפשרויות) או וריאציה
5. \`[ סעיף ד' - שאלה פתוחה ]\` או וריאציה

## סוגי שאלה
- \`* סוג השאלה: Single Choice\` — 2 אפשרויות (סעיפים א, ב)
- \`* סוג השאלה: Single Choice (3 Options)\` — 3 אפשרויות (סעיף ג)
- \`* סוג השאלה: Open Ended\` — שאלה פתוחה (סעיף ד)

## שדות בתוך בלוק "נתוני פתיחה"
- \`* טקסט: <פסקת פתיחה של התרגיל>\` — מבוא קצר, מוסיף הקשר.
- \`* שרטוט בסיס (מבנה אובייקטים):\` — אופציונלי, שרטוט משותף לכל הסעיפים.

## שדות בתוך בלוק סעיף
- \`* סוג השאלה: <sig>\` — חובה
- \`* הנחיה: <השאלה>\` — חובה. השאלה בעברית, ברורה, ממוקדת.
- \`* שרטוט מותאם לסעיף:\` — אופציונלי, שרטוט ספציפי לסעיף (יכול לרשת את שרטוט הבסיס).
- \`* אפשרות 1: <text>\` — לסעיפי MCQ. סמן את התשובה הנכונה עם **[תשובה נכונה]** בסוף השורה.
- \`* אפשרות 2: <text>\`
- \`* אפשרות 3: <text>\` — רק בסעיף ג
- \`* פתרון מלא: <הסבר>\` — אופציונלי אך מומלץ, מסביר איך מגיעים לתשובה.
- \`* רמז: <רמז>\` — אופציונלי.

## חוקי סימון תשובה נכונה
- **בדיוק אחת** מהאפשרויות בסעיפי MCQ מסומנת עם \`[תשובה נכונה]\` בסוף השורה.
- אין רווח נוסף אחרי \`נכונה]\` — הכולה חייבת להיות בסוף השורה בדיוק.
- **בשאלות פתוחות (סעיף ד)** — אין אפשרויות ואין [תשובה נכונה]. במקום זה יש \`* פתרון מלא:\` שמראה תשובה לדוגמה או קריטריון להערכה.

## שרטוטים — תיאור חופשי (חשוב מאוד!)

**אתה לא כותב DSL או SVG בעצמך.** יש שלב הבא במערכת — Materializer — שמומחה בפריסת שרטוטים. תפקידך: לתאר בעברית חופשית **מה** אמור להיות בשרטוט, ולתת לו לפרוס.

### פורמט התיאור החופשי
השתמש בבלוק פתיחה וסגירה \`{{SKETCH BEGIN}}\` ו-\`{{SKETCH END}}\`. תוכן הבלוק — תיאור מילולי חופשי בעברית של הצורה, האובייקטים, הצבעים, והסימונים.

### דוגמה — שרטוט גיאומטרי
\`\`\`
* שרטוט מותאם לסעיף:
{{SKETCH BEGIN}}
מלבן ABCD רחב (יחס רוחב:גובה = 2:1). אלכסון AC בצבע כחול. גובה BH מ-B ל-AC בצבע אדום, כאשר H נמצאת על AC. סמן זווית ישרה בקודקוד H.
{{SKETCH END}}
\`\`\`

### דוגמה — שרטוט פיקטוריאלי (סולם ליד קיר)
\`\`\`
* שרטוט מותאם לסעיף:
{{SKETCH BEGIN}}
קיר אנכי אפור בצד שמאל. קרקע חומה אופקית. סולם ירוק באורך 5 מטר משופע, קצהו העליון נוגע בקיר בגובה מסוים, קצהו התחתון מונח על הקרקע במרחק 3 מטר מהקיר. תווית על הסולם: "5 מ'", תווית על המרחק על הקרקע: "3 מ'".
{{SKETCH END}}
\`\`\`

### כללים לתיאור החופשי
- **פרט את הצורה**: משולש, מלבן, מקבילית, ריבוע. אם יש מידות יחסיות (רחב, שווה-שוקיים) — ציין.
- **שם את הנקודות** באותיות (A, B, C, H). אם יש נקודה נגזרת (כמו רגל הגובה, אמצע קטע) — הסבר איך היא נגזרת.
- **צבעים ותוויות** — ציין רק את מה שחשוב לפדגוגיה: "אלכסון בצבע כחול", "צלע 5 עם תווית", "זווית 60° מסומנת בירוק".
- **אל תכתוב קואורדינטות** — המטריאלייזר יחשב אותן.
- **אל תמציא DSL** — פשוט תאר במילים.
- **תמציתי אבל שלם** — 1-3 משפטים לרוב מספיקים.

### מתי להשתמש בשרטוט?
- כל visualStyle לא-ריק בשלד → סעיף נתוני פתיחה מקבל \`* שרטוט בסיס:\` + \`{{SKETCH BEGIN}}…{{SKETCH END}}\`.
- אם סעיף (א/ב/ג/ד) צריך שרטוט משלו — הוסף \`* שרטוט מותאם לסעיף:\` + בלוק סקטש.
- **אל תשכפל את השרטוט** בכל סעיף אם הוא זהה לשרטוט הבסיס — הוא יורש אותו.

# איך להפוך שלד לתוכן מלא

## מבנה הסעיף
- **briefPrompt** בשלד = משפט מהות. הרחב אותו להנחיה מלאה עם הקשר.
- **expectedDiscovery** בשלד = מה התלמיד צריך לגלות. השתמש בזה כדי לנסח את \`פתרון מלא:\`.
- **visualStyle** בשלד = תיאור מילולי של השרטוט. הפוך אותו לשרטוט DSL או SVG.

## יצירת אפשרויות ה-MCQ
- אפשרות אחת נכונה (סומן \`[תשובה נכונה]\`), 1-2 מסיחים (distractors).
- **מסיחים חייבים להיות סבירים** — טעויות אופייניות של תלמידים, לא אבסורדיים.
  - דוגמה טובה: לשאלת "0 × 11 = ?" הנכונה 0, המסיח 11 (טעות של "כפל ב-0 לא משנה").
  - דוגמה רעה: לאותה שאלה, מסיח "פינגווין" — אבסורדי.
- **סעיפי א' וב'**: 2 אפשרויות. שאלה בינארית ("האם X או Y?").
- **סעיף ג'**: 3 אפשרויות. הכנס מסיח נוסף — לרוב טעות מסוג שני.

## סעיף ד' (שאלה פתוחה) — כללים חשובים
- **אסור**: הנחיה שמתחילה ב-"הסבר", "תאר במילים". במקום זה: "מצאו", "בנו", "ציירו", "הציבו".
- **תמיד** כלול \`* פתרון מלא:\` שנותן תשובה לדוגמה או קריטריון להערכה.

## סגנון ניסוח
- כתוב בגוף ראשון רבים ("אנחנו נשווה", "נבחין") או בציווי ("מצאו", "בחרו").
- **אל תשתמש** ב-"התלמיד/ה יבין/תבין" — מבלגן את הטקסט.
- שפה ברורה, מותאמת לגיל בכיתה.

## שמירה על סקופ הגיל
- בכיתה ז': אין x², אין ריבועיות, אין הוכחות פורמליות.
- בכיתה ח': אין פונקציות מפורשות, אין ניתוח מקרים.
- אל תסטה מהתחום שהשלד קבע.

# דוגמה מרוכזת של הפורמט (משיעור אמיתי, לא כל 10 התרגילים — רק דוגמה של תרגיל 1 שלם)

${V2_FORMAT_REFERENCE}

# מה אתה מחזיר

תוכן .txt מלא של השיעור — כל 10 התרגילים, כל תרגיל עם בלוק "נתוני פתיחה" + 4 סעיפים.

**חשוב מאוד:**
- כתוב **את התוכן בלבד** — ללא הסברים לפני או אחרי, ללא code fences של markdown, ללא הערות.
- הפורמט חייב להיות תקף — הפלט שלך יעבור פרסר אוטומטי (\`parseTextLessonV2\`).
- כל 10 התרגילים חייבים להיות בפלט — לא לקצר או לדלג.
- כל תרגיל חייב לכלול את 4 הסעיפים א', ב', ג', ד' — לא לדלג.
`

export function buildWriterSystemPrompt(): string {
  return SYSTEM_PROMPT
}

export function buildWriterUserPrompt(skeleton: LessonSkeleton): string {
  const lines: string[] = []
  lines.push(`# שלד השיעור לכתיבה`)
  lines.push('')
  lines.push(`**שם השיעור**: ${skeleton.lessonName}`)
  lines.push(`**קורס**: ${skeleton.course}`)
  lines.push(`**פרק**: ${skeleton.chapter}`)
  lines.push(`**מטרת השיעור**: ${skeleton.lessonObjective}`)
  lines.push(`**ידע קודם (התלמיד יודע)**: ${skeleton.priorKnowledgeKnown || '(לא פורט)'}`)
  lines.push(`**ידע קודם (לא להניח שיודע)**: ${skeleton.priorKnowledgeAssumeNot || '(לא פורט)'}`)
  lines.push(`**גבולות השיעור (לא ללמד)**: ${skeleton.lessonBoundaries || '(לא פורט)'}`)
  lines.push('')
  lines.push(`## התרגילים:`)
  lines.push('')
  for (const ex of skeleton.exercises) {
    lines.push(`### תרגיל ${ex.number}`)
    lines.push(`- **objective**: ${ex.objective}`)
    lines.push(`- **oneNewThing**: ${ex.oneNewThing}`)
    lines.push(`- **visualStyle**: ${ex.visualStyle || '(ללא)'}`)
    for (const sec of ex.sections) {
      lines.push(`  - **סעיף ${sec.letter}' (${sec.shape})**:`)
      lines.push(`    - briefPrompt: ${sec.briefPrompt}`)
      lines.push(`    - expectedDiscovery: ${sec.expectedDiscovery}`)
    }
    lines.push('')
  }
  lines.push('')
  lines.push(
    `כתוב את התוכן המלא של השיעור בפורמט v2. הפלט חייב להתחיל ב-\`=========================================\` של תרגיל 1 ולהסתיים אחרי תרגיל 10. **תוכן בלבד — ללא הסברים, ללא markdown fences**.`,
  )
  return lines.join('\n')
}
